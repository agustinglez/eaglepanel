/** App number: defines its namespace and its private address, 10.88.0.0/16 split into /30 blocks. */
export const appIdSchema = z.number().int().min(1).max(16383);

/**
 * HTTPS or SSH only. `file://` and similar are excluded: the agent clones as root, and a local path would let it
 * read any repository on the server. No username or password in the URL: that is what the key is for.
 */
export const repoUrlSchema = z.string().max(300).refine((value) =>
  /^https:\/\/[a-z0-9.-]+(?::\d{2,5})?\/[A-Za-z0-9._~/-]+$/.test(value)
  || /^git@[a-z0-9.-]+:[A-Za-z0-9._~/-]+$/.test(value)
  || /^ssh:\/\/git@[a-z0-9.-]+(?::\d{2,5})?\/[A-Za-z0-9._~/-]+$/.test(value),
"Use an HTTPS or SSH URL, such as https://github.com/user/repo.git or git@github.com:user/repo.git");

export const isSshRepo = (url: string) => !url.startsWith("https://");

/** Branch name. Passed as an argument to git: it cannot start with a dash or contain "..". */
export const branchSchema = z.string().regex(/^[A-Za-z0-9._][A-Za-z0-9._/-]{0,99}$/, "Invalid branch").refine((value) => !value.includes(".."), "Invalid branch");

/** Repository subdirectory, for monorepos. Empty means the root. */
export const repoSubdirSchema = z.union([z.literal(""), docRootSchema]);

export const appRuntimeSchema = z.enum(["node", "bun"]);
export type AppRuntime = z.infer<typeof appRuntimeSchema>;
/**
 * For now every app runs with Bun (user decision). Node will be added when the panel goes public: it stays in
 * the schema without versions. The version is the series of the official image: every deployment gets the latest of the series.
 */
export const RUNTIME_VERSIONS: Record<AppRuntime, string[]> = { node: [], bun: ["1"] };
export const runtimeVersionSchema = z.string().regex(/^\d{1,2}$/, "Invalid version");

/**
 * Like Cloudflare: `static` is Pages (built, and OLS serves the result without any process) and `server` is
 * Workers (a process that serves requests, in its container).
 */
export const appKindSchema = z.enum(["static", "server"]);
export type AppKind = z.infer<typeof appKindSchema>;

/** Run by the account, in its container. No line breaks: each command goes in a one-line script. */
export const appCommandSchema = z.string().max(500).refine((value) => !/[\r\n\0]/.test(value), "The command cannot contain line breaks");
export const healthPathSchema = z.string().max(200).regex(/^\/[A-Za-z0-9._~/?=&%-]*$/, "Must start with / and be a simple path");
export const appMemorySchema = z.number().int().min(64, "The minimum is 64 MB").max(8192);
/** Directory the build produces and OLS publishes. Empty means the project root. */
export const outputDirSchema = z.union([z.literal(""), docRootSchema]);

/** A start command that rebuilds: every restart would take as long as the build. Warned about, not blocked. */
export const startRebuilds = (command: string) =>
  /\brun\s+build\b|\b(next|vite|astro|nuxt)\s+build\b|\binstall\b/.test(command) || /\b(npm|bun|pnpm|yarn)\s+(i|ci)\b/.test(command);

/** The panel sets these: the app cannot override them. NODE_ENV is not here: production by default, the app may change it. */
export const RESERVED_ENV = new Set(["PORT", "HOSTNAME", "HOME", "DATA_DIR", "PATH"]);
export const envKeySchema = z.string().regex(/^[A-Z_][A-Z0-9_]{0,63}$/, "Uppercase letters, digits and underscores, not starting with a digit")
  .refine((value) => !RESERVED_ENV.has(value), { error: (issue) => `${String(issue.input)} is set by the panel` });
export const envValueSchema = z.string().max(32 * 1024).refine((value) => !value.includes("\0"), "Invalid value");
export const envScopeSchema = z.enum(["runtime", "build", "both"]);
export type EnvScope = z.infer<typeof envScopeSchema>;
export const envVarsSchema = z.record(envKeySchema, envValueSchema);

/**
 * A build command and a start command, like Workers: whoever owns the app knows how it is built and run.
 * The build runs once per deployment; the start command, on every start. A static site has no start command or memory.
 */
export const appConfigSchema = z.object({
  kind: appKindSchema,
  repoUrl: repoUrlSchema,
  branch: branchSchema,
  subdir: repoSubdirSchema,
  runtime: appRuntimeSchema,
  runtimeVersion: runtimeVersionSchema,
  buildCommand: appCommandSchema,
  startCommand: appCommandSchema,
  outputDir: outputDirSchema,
  /** Static sites only: paths that are not files return index.html, as in an SPA. */
  spaFallback: z.boolean(),
  healthPath: healthPathSchema,
  memoryMb: z.number().int().min(0).max(8192),
}).strict()
  .refine((config) => RUNTIME_VERSIONS[config.runtime].includes(config.runtimeVersion), { message: "That version is not available", path: ["runtimeVersion"] })
  .refine((config) => config.kind === "static" || config.startCommand.trim().length > 0, { message: "The start command is required", path: ["startCommand"] })
  .refine((config) => config.kind === "static" || config.memoryMb >= 64, { message: "The minimum is 64 MB", path: ["memoryMb"] })
  .refine((config) => config.kind === "server" || config.buildCommand.trim().length > 0 || config.outputDir === "", { message: "Without a build, the output directory is the project root", path: ["outputDir"] });
export type AppConfig = z.infer<typeof appConfigSchema>;

/** Memory an app reserves: a static site runs no process. */
export const appReservedMemory = (config: Pick<AppConfig, "kind" | "memoryMb">) => (config.kind === "server" ? config.memoryMb : 0);

/** Host-side and app-side address for an id. */
export function appAddresses(id: number): { host: string; app: string } {
  const base = id * 4;
  const prefix = `10.88.${Math.floor(base / 256)}`;
  return { host: `${prefix}.${(base % 256) + 1}`, app: `${prefix}.${(base % 256) + 2}` };
}
