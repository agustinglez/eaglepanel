import { ACCOUNT_HOOK_PATH, APP_PORT, appAddresses, GLOBAL_HOOK_PATH, PANEL_API_PORT, type AgentOpParams, type LogLevel, type PhpOptions } from "@eaglepanel/shared";

export const LSWS = "/usr/local/lsws";
export const HTTPD_CONFIG = `${LSWS}/conf/httpd_config.conf`;
export const CERTS_DIR = `${LSWS}/conf/eaglepanel-certs`;

const BLOCK_BEGIN = "# BEGIN EAGLEPANEL: generated by the panel, do not edit by hand";
/** Found by this prefix: servers installed before the English text keep a Spanish comment after it. */
const BLOCK_MARK = "# BEGIN EAGLEPANEL";
const BLOCK_END = "# END EAGLEPANEL";

/** Functions not needed by a normal site that allow running system commands. */
const DISABLED_FUNCTIONS = "exec,passthru,shell_exec,system,proc_open,popen,pcntl_exec";

/**
 * Directory lsphp reads at startup, writable by root only. Measured on the VPS: `disable_functions` in
 * phpIniOverride has no effect, and exec() keeps working. It only applies from an .ini loaded at startup.
 * It must never point to an account directory: there, a .user.ini re-enabled exec().
 */
export const PHP_SYSTEM_INI_DIR = "/etc/eaglepanel/php";
export const PHP_SYSTEM_INI = `${PHP_SYSTEM_INI_DIR}/90-eaglepanel.ini`;
export const PHP_SYSTEM_INI_CONTENT = `; Generado por EaglePanel. No editar a mano.
disable_functions=${DISABLED_FUNCTIONS}
`;
/** With the default 300 s, a change in .user.ini was not visible until lsphp restarted. At 6 s it was already applied. */
const USER_INI_CACHE_TTL = 5;
export const userIniPath = (username: string, docRoot: string) => `/home/${username}/${docRoot}/.user.ini`;

type ErrorLevel = PhpOptions["directives"]["error_reporting"];
/** `php_value` receives text and PHP does not evaluate constants there, unlike in `php.ini`: the number goes in. */
const ERROR_REPORTING_VALUES: Record<ErrorLevel, number> = { E_ALL: 32767, "E_ALL & ~E_DEPRECATED": 24575, E_ERROR: 1 };

export interface SiteConfig {
  username: string;
  site: string;
  /** Relative to the account home directory. */
  docRoot: string;
  phpVersion: string;
  phpOptions: PhpOptions;
  certZone: string | null;
  originPull: boolean;
  logLevel: LogLevel;
  logDays: number;
  suspended: boolean;
  app: AgentOpParams<"site.write">["app"];
  hooks: boolean;
}

/** What the agent finds out on the server before writing the vhost. */
export interface SiteFacts {
  /** A static site's published release has `assets/`: hashed files that are cached forever. */
  immutableAssets: boolean;
  /** Output directory of a static site. Computed by the agent: OLS reads it as is. */
  staticRoot: string | null;
}

export interface SyncedSite {
  site: string;
  username: string;
  hostname: string;
  certZone: string | null;
  originPull: boolean;
}

export const ORIGIN_PULL_CA_PATH = `${CERTS_DIR}/cloudflare-origin-pull-ca.pem`;
/** Tested with this CA on the VPS: its chain needs depth 2. */
const originPullSsl = `  clientVerify            2
  verifyDepth             2
  CACertFile              ${ORIGIN_PULL_CA_PATH}
`;

export const vhostDir = (site: string) => `${LSWS}/conf/vhosts/${site}`;
/** Outside the home directory: the account cannot change or delete what OLS writes, which runs with more privileges. */
export const vhostLogDir = (site: string) => `/var/log/eaglepanel/vhosts/${site}`;
/** Initial value, in the home directory. It belongs to the account, as on any hosting: it can change or delete it. If moved, the panel stops rotating it. */
export const phpLogDir = (username: string, site: string) => `/home/${username}/sites/${site}/logs`;
export const phpLogPath = (username: string, site: string) => `${phpLogDir(username, site)}/php_error.log`;
/** `.conf` because logrotate skips certain suffixes. */
export const logrotatePath = (site: string) => `/etc/logrotate.d/eaglepanel-${site}.conf`;

/**
 * OLS logs: its own rotation did not act at 10 KB on the VPS, not even with the directory owned by its user. With
 * copytruncate, OLS keeps writing without leaving a sparse file.
 *
 * PHP error_log: packed into a tar.gz when it reaches 20 MB or once a month, inside the environment logs/, and the panel does not
 * delete those files: they belong to the account and count toward its quota. `su` is not enough for packing: tested on
 * the VPS, postrotate still runs as root, in a directory the account controls. That is why it uses setpriv.
 */
export function renderLogrotate({ username, site, logDays, app }: Pick<SiteConfig, "username" | "site" | "logDays" | "app">): string {
  const phpLog = phpLogPath(username, site);
  const phpLogName = phpLog.slice(phpLog.lastIndexOf("/") + 1);
  const pack = `cd ${phpLogDir(username, site)} || exit 1; for f in ${phpLogName}-*; do case "$f" in *.tar.gz) continue ;; esac; if [ -f "$f" ] && [ ! -L "$f" ]; then tar -czf "$f.tar.gz" -- "$f" && rm -f -- "$f"; fi; done`;
  return `${vhostLogDir(site)}/*.log {
  daily
  rotate ${logDays}
  maxage ${logDays}
  missingok
  notifempty
  compress
  delaycompress
  copytruncate
}
${app ? "" : `
${phpLog} {
  su ${username} ${username}
  monthly
  maxsize 20M
  rotate -1
  missingok
  notifempty
  nocompress
  copytruncate
  dateext
  dateformat -%Y%m%d-%s
  postrotate
    /usr/bin/setpriv --reuid=${username} --regid=${username} --clear-groups /bin/sh -c '${pack}'
  endscript
}
`}`;
}
export const certPath = (zone: string) => `${CERTS_DIR}/${zone}/origin.crt`;
export const keyPath = (zone: string) => `${CERTS_DIR}/${zone}/origin.key`;

/**
 * Empty root-owned directory. Measured on the VPS: even without the 503 rule, the worst case is a 404, never the account code.
 * It cannot be in /etc: OLS rejects that docRoot ("Path is in the access denied list") and the vhost does not load.
 */
export const SUSPENDED_DOC_ROOT = "/srv/eaglepanel/empty";

/** Keeps certificate and logs: without the certificate, Cloudflare would answer 526 instead of the 503. */
function renderSuspendedVhost({ site, logLevel, ssl }: Pick<SiteConfig, "site" | "logLevel"> & { ssl: string }): string {
  return `docRoot                   ${SUSPENDED_DOC_ROOT}

errorlog ${vhostLogDir(site)}/error.log {
  useServer               0
  logLevel                ${logLevel}
  rollingSize             0
}

accesslog ${vhostLogDir(site)}/access.log {
  useServer               0
  logFormat               %h %l %u %t "%r" %>s %b
  rollingSize             0
}

rewrite  {
  enable                  1
  rules                   <<<END_rules
RewriteRule ^ - [R=503,L]
END_rules
}
${ssl}`;
}

/**
 * Proxy to the app in its namespace. Validated on the VPS through OLS and Cloudflare: without the `websocket` block,
 * OLS answers 101 but does not pass messages. Dot files are handled by the app: here OLS serves no files.
 * The port is always the same: inside the namespace it is redirected to the active slot, so switching releases does not
 * touch this file or restart OLS.
 */
function renderAppVhost({ site, logLevel, appId, redirect, ssl, hooks }: Pick<SiteConfig, "site" | "logLevel" | "hooks"> & { appId: number; redirect: string; ssl: string }): string {
  const address = `${appAddresses(appId).app}:${APP_PORT}`;
  return `docRoot                   ${SUSPENDED_DOC_ROOT}
enableGzip                1
${logBlocks(site, logLevel)}
extprocessor app-${appId} {
  type                    proxy
  address                 ${address}
  maxConns                100
  pcKeepAliveTimeout      60
  initTimeout             120
  retryTimeout            0
  respBuffer              0
}

websocket / {
  address                 ${address}
}

# OLS 1.9.4 duplicates X-Forwarded-Proto when it arrives as https (the app saw "https, https"). With unset only
# one remains, the one OLS adds back; a value other than https does not get through. set does not help: OLS adds it anyway.
context / {
  type                    proxy
  handler                 app-${appId}
  addDefaultCharset       off
  extraHeaders            RequestHeader unset X-Forwarded-Proto
}
${hooks ? accountHooks : ""}${redirect}${ssl}`;
}

const HTTPS_REDIRECT = `RewriteCond %{HTTPS} !on
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
`;

/**
 * Static site, like Cloudflare Pages: OLS serves the published release and runs no process. Validated on the
 * VPS with a real front end: the SPA route returns index.html, a missing asset returns 404 and dot files,
 * 403. The fallback looks at Accept, like the Workers SPA mode: only a navigation receives index.html, and a missing
 * script or image does not arrive as a 200 with HTML inside.
 */
function renderStaticVhost({ site, logLevel, root, spaFallback, immutableAssets, certZone, ssl, hooks }: Pick<SiteConfig, "site" | "logLevel" | "certZone" | "hooks"> & {
  root: string | null; spaFallback: boolean; immutableAssets: boolean; ssl: string;
}): string {
  const redirect = certZone ? HTTPS_REDIRECT : "";
  // No published release yet: the same as an app before its first deployment.
  if (!root) {
    return `docRoot                   ${SUSPENDED_DOC_ROOT}
${logBlocks(site, logLevel)}
rewrite  {
  enable                  1
  rules                   <<<END_rules
${redirect}RewriteRule ^ - [R=503,L]
END_rules
}
${ssl}`;
  }
  const spa = spaFallback
    ? `RewriteCond %{HTTP_ACCEPT} text/html
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^ /index.html [L]
`
    : "";
  const assets = immutableAssets
    ? `
context /assets/ {
  location                $DOC_ROOT/assets/
  allowBrowse             1
  extraHeaders            Header set Cache-Control "public, max-age=31536000, immutable"
}
`
    : "";
  return `docRoot                   ${root}
enableGzip                1
${logBlocks(site, logLevel)}
index  {
  useServer               0
  indexFiles              index.html
}

# Dot files and directories: the panel does not publish them, and this covers anything that slips through.
context exp:(^|/)\\.(?!well-known(/|$)) {
  allowBrowse             0
}
${assets}${hooks ? accountHooks : ""}
rewrite  {
  enable                  1
  autoLoadHtaccess        0
  rules                   <<<END_rules
${redirect}RewriteRule (^|/)\\.(?!well-known(/|$)) - [F]
${spa}END_rules
}
${ssl}`;
}

function logBlocks(site: string, logLevel: LogLevel): string {
  return `
errorlog ${vhostLogDir(site)}/error.log {
  useServer               0
  logLevel                ${logLevel}
  rollingSize             0
}

accesslog ${vhostLogDir(site)}/access.log {
  useServer               0
  logFormat               %h %l %u %t "%r" %>s %b
  rollingSize             0
}
`;
}

export function renderVhost(
  { username, site, docRoot, phpVersion, phpOptions, certZone, originPull, logLevel, suspended, app, hooks }: SiteConfig,
  facts: SiteFacts = { immutableAssets: false, staticRoot: null },
): string {
  const home = `/home/${username}`;
  const { children, memoryMb, indexFiles, gzip, htaccess, directives, flags } = phpOptions;
  // First what the user chose: the security directives, which come after, always win.
  const userIni = [
    `  php_value error_log "${phpLogPath(username, site)}"`,
    ...Object.entries(directives).map(([key, value]) => `  php_value ${key} "${key === "error_reporting" ? ERROR_REPORTING_VALUES[value as ErrorLevel] : value}"`),
    ...Object.entries(flags).map(([key, value]) => `  php_flag ${key} ${value ? "on" : "off"}`),
  ].join("\n");
  // The client certificate is only requested on 443: without this redirect, port 80 would serve the site without requiring it.
  // Without a certificate there is no redirect, because over HTTPS that environment does not exist yet.
  const redirectRules = certZone
    ? `  rules                   <<<END_rules
RewriteCond %{HTTPS} !on
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
END_rules
`
    : "";
  const rewrite = htaccess || certZone
    ? `
rewrite  {
  enable                  1
${htaccess ? "  autoLoadHtaccess        1\n" : ""}${redirectRules}}
`
    : "";
  const ssl = certZone
    ? `
vhssl  {
  keyFile                 ${keyPath(certZone)}
  certFile                ${certPath(certZone)}
  certChain               0
${originPull ? originPullSsl : ""}}
`
    : "";

  if (suspended) return renderSuspendedVhost({ site, logLevel, ssl });
  if (app?.kind === "server") return renderAppVhost({ site, logLevel, appId: app.id, redirect: certZone ? rewrite : "", ssl, hooks });
  if (app?.kind === "static") {
    return renderStaticVhost({ site, logLevel, certZone, ssl, hooks, root: facts.staticRoot, spaFallback: app.spaFallback, immutableAssets: facts.immutableAssets });
  }

  return `docRoot                   ${home}/${docRoot}
enableGzip                ${gzip ? 1 : 0}

errorlog ${vhostLogDir(site)}/error.log {
  useServer               0
  logLevel                ${logLevel}
  rollingSize             0
}

accesslog ${vhostLogDir(site)}/access.log {
  useServer               0
  logFormat               %h %l %u %t "%r" %>s %b
  rollingSize             0
}

index  {
  useServer               0
  indexFiles              ${indexFiles}
}
${rewrite}
phpIniOverride  {
${userIni}
  php_admin_value open_basedir "${home}"
  php_admin_value upload_tmp_dir "${home}/tmp"
  php_admin_value session.save_path "${home}/tmp"
  php_admin_value user_ini.cache_ttl "${USER_INI_CACHE_TTL}"
  php_admin_flag allow_url_include off
}
${hooks ? accountHooks : ""}
# Dot files and directories: without this, OLS serves .env, .git/ or .user.ini to anyone.
# .well-known is excluded because it is the standard for domain validation.
context exp:(^|/)\\.(?!well-known(/|$)) {
  allowBrowse             0
}

extprocessor lsphp-${site} {
  type                    lsapi
  address                 uds://tmp/lshttpd/${site}.sock
  maxConns                ${children}
  env                     PHP_LSAPI_CHILDREN=${children}
  env                     LSAPI_AVOID_FORK=200M
  env                     LSPHP_ENABLE_USER_INI=on
  env                     PHP_INI_SCAN_DIR=:${PHP_SYSTEM_INI_DIR}
  initTimeout             60
  retryTimeout            0
  persistConn             1
  respBuffer              0
  autoStart               2
  path                    ${LSWS}/lsphp${phpVersion}/bin/lsphp
  backlog                 100
  instances               1
  extUser                 ${username}
  extGroup                ${username}
  priority                0
  memSoftLimit            ${memoryMb}M
  memHardLimit            ${Math.round(memoryMb * 1.5)}M
  procSoftLimit           100
  procHardLimit           150
}

scripthandler  {
  add                     lsapi:lsphp-${site} php
}
${ssl}`;
}

